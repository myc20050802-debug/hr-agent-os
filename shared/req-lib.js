  /* 字符 bigram 集合 —— 用于「行业语境句是否与已有职责重复」的判定 */
  function bigrams(s) {
    const x = norm(s);
    const out = new Set();
    for (let i = 0; i < x.length - 1; i++) out.add(x.slice(i, i + 2));
    return out;
  }
  /* 最长公共子串长度 —— 判定「整句近似重复」比 bigram 覆盖率更准
     （行业句与职能句往往共用一两个长短语，而不是整体重合）。 */
  function lcsLen(a, b) {
    const x = norm(a), y = norm(b);
    if (!x || !y) return 0;
    let best = 0;
    const dp = new Array(y.length + 1).fill(0);
    for (let i = 1; i <= x.length; i++) {
      let prev = 0;
      for (let j = 1; j <= y.length; j++) {
        const tmp = dp[j];
        dp[j] = x[i - 1] === y[j - 1] ? prev + 1 : 0;
        if (dp[j] > best) best = dp[j];
        prev = tmp;
      }
    }
    return best;
  }
  /* 行业语境句：与已选职责去重后才追加，避免「同一件事在 JD 里说两遍」。
     两道闸：① 与某条职责存在 ≥8 字的公共子串（近似整句重复）；
             ② 与某条职责的 bigram 重合度 ≥0.5（相对较短者）。
     行业句写成「指标 + 行话」口径，与职能句（动作口径）天然互补，
     正常不会被误杀；被拦只说明该职能族本身已完整覆盖了行业表达。 */
  function industryDuty(industry, duties, fnKey) {
    const ctx = INDUSTRY_CTX[industry];
    if (!ctx || !ctx.duty) return '';
    /* 适配闸（v13，配合上方 fit 白名单）：职责句与岗位职能对不上就整句不拼。
       fnKey 未传（认不出职能）同样不拼 —— 此时职责本就回落到行业通用模板，
       再叠一句主力职能口径的行话只会更错位。 */
    if (ctx.fit && ctx.fit.length && (!fnKey || ctx.fit.indexOf(fnKey) < 0)) return '';
    const cb = bigrams(ctx.duty);
    const dup = (duties || []).some(d => {
      if (lcsLen(ctx.duty, d) >= 8) return true;
      const db = bigrams(d);
      if (!db.size || !cb.size) return false;
      let inter = 0;
      cb.forEach(g => { if (db.has(g)) inter++; });
      return inter / Math.min(cb.size, db.size) >= 0.5;
    });
    return dup ? '' : ctx.duty;
  }

